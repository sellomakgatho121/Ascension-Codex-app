// Search UTM knowledge
export function searchUTMKnowledge(query: string, category?: string): TimeMatrixConcept[] {
  const searchTerm = query.toLowerCase();
  
  return universalTimeMatrixKnowledge.filter(concept => {
    const matchesCategory = !category || concept.category === category;
    const matchesSearch = 
      concept.title.toLowerCase().includes(searchTerm) ||
      concept.description.toLowerCase().includes(searchTerm) ||
      concept.details.toLowerCase().includes(searchTerm) ||
      concept.relatedConcepts.some(term => term.toLowerCase().includes(searchTerm));
    
    return matchesCategory && matchesSearch;
  });
}

