// Blog content organization and navigation functions
export function getBlogPostsByCategory(category: string): BlogPost[] {
  return timelineShiftBlogPosts.filter(post => post.category === category);
}

export function getBlogPostsByLevel(level: string): BlogPost[] {
  return timelineShiftBlogPosts.filter(post => post.progressionLevel === level);
}

export function getBlogPostsByTopic(topic: string): BlogPost[] {
  return timelineShiftBlogPosts.filter(post => 
    post.keyTopics.some(t => t.toLowerCase().includes(topic.toLowerCase())) ||
    post.relatedConcepts.some(c => c.toLowerCase().includes(topic.toLowerCase()))
  );
}

export function searchBlogPosts(query: string): BlogPost[] {
  const searchTerm = query.toLowerCase();
  return timelineShiftBlogPosts.filter(post =>
    post.title.toLowerCase().includes(searchTerm) ||
    post.summary.toLowerCase().includes(searchTerm) ||
    post.content.toLowerCase().includes(searchTerm) ||
    post.keyTopics.some(topic => topic.toLowerCase().includes(searchTerm)) ||
    post.tags.some(tag => tag.toLowerCase().includes(searchTerm))
  );
}

export function getRelatedBlogPosts(postId: string, limit: number = 3): BlogPost[] {
  const currentPost = timelineShiftBlogPosts.find(p => p.id === postId);
  if (!currentPost) return [];
  
  return timelineShiftBlogPosts
    .filter(post => post.id !== postId)
    .filter(post => 
      post.category === currentPost.category ||
      post.keyTopics.some(topic => currentPost.keyTopics.includes(topic)) ||
      post.relatedConcepts.some(concept => currentPost.relatedConcepts.includes(concept))
    )
    .slice(0, limit);
}

