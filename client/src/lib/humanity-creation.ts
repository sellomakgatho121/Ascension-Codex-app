// Get events by category
export function getEventsByCategory(category: string): CreationEvent[] {
  return humanityCreationTimeline.filter(event => event.category === category);
}

// Get events by timeframe
export function getEventsByTimeframe(startYear: number, endYear: number): CreationEvent[] {
  return humanityCreationTimeline.filter(event => {
    // Simple timeframe filtering - could be enhanced with more sophisticated parsing
    return event.timeframe.includes('Years Ago') || 
           event.timeframe.includes('CE') || 
           event.timeframe.includes('BCE');
  });
}

// Get related events
export function getRelatedEvents(eventId: string): CreationEvent[] {
  const event = humanityCreationTimeline.find(e => e.id === eventId);
  if (!event) return [];
  
  return humanityCreationTimeline.filter(e => 
    e.id !== eventId && 
    e.relatedConcepts.some(concept => 
      event.relatedConcepts.includes(concept)
    )
  ).slice(0, 3);
}