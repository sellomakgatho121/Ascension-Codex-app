// Combine with original knowledge base
export const completeESKnowledgeBase = [...expandedESKnowledgeBase];

// Enhanced search function for expanded knowledge base
export function searchExpandedESKnowledge(query: string, category?: string): ESConcept[] {
  const searchTerm = query.toLowerCase();
  
  return completeESKnowledgeBase.filter(concept => {
    const matchesCategory = !category || concept.category === category;
    const matchesSearch = 
      concept.term.toLowerCase().includes(searchTerm) ||
      concept.definition.toLowerCase().includes(searchTerm) ||
      concept.relatedTerms.some(term => term.toLowerCase().includes(searchTerm)) ||
      concept.applications.some(app => app.toLowerCase().includes(searchTerm));
    
    return matchesCategory && matchesSearch;
  });
}