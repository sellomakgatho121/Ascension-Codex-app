import * as React from "react"

import { cn } from "@/lib/utils"
import { motion, useMotionValue, useSpring, useTransform } from "framer-motion"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & {
    variant?: "default" | "glass" | "elevated" | "flat"
  }
>(({ className, variant = "default", ...props }, ref) => {
  const x = useMotionValue(0)
  const y = useMotionValue(0)

  const mouseXSpring = useSpring(x)
  const mouseYSpring = useSpring(y)

  const rotateX = useTransform(mouseYSpring, [-0.5, 0.5], ["10deg", "-10deg"])
  const rotateY = useTransform(mouseXSpring, [-0.5, 0.5], ["-10deg", "10deg"])

  const handleMouseMove = (e: React.MouseEvent<HTMLDivElement>) => {
    const rect = e.currentTarget.getBoundingClientRect()
    const width = rect.width
    const height = rect.height
    const mouseX = e.clientX - rect.left
    const mouseY = e.clientY - rect.top
    const xPct = mouseX / width - 0.5
    const yPct = mouseY / height - 0.5
    x.set(xPct)
    y.set(yPct)
  }

  const handleMouseLeave = () => {
    x.set(0)
    y.set(0)
  }

  return (
    <motion.div
      ref={ref}
      style={{
        rotateX,
        rotateY,
        transformStyle: "preserve-3d",
      }}
      onMouseMove={handleMouseMove}
      onMouseLeave={handleMouseLeave}
      whileHover={{ scale: 1.01, z: 20 }}
      className={cn(
        "rounded-xl transition-all duration-300",
        variant === "default" && "border border-white/10 bg-cosmic-800/50 backdrop-blur-glass shadow-lg hover:shadow-glow",
        variant === "glass" && "glass hover:shadow-glow",
        variant === "elevated" && "border border-white/10 bg-cosmic-800/80 backdrop-blur-glass shadow-2xl hover:shadow-glow-strong",
        variant === "flat" && "bg-cosmic-800/30 border-none",
        className
      )}
      {...props}
    />
  )
})
Card.displayName = "Card"

